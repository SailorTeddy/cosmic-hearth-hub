/** Stable hash → 32-bit int */
function h(...parts) {
  let x = 2166136261;
  for (const p of parts) {
    const s = String(p);
    for (let i = 0; i < s.length; i++) {
      x ^= s.charCodeAt(i);
      x = Math.imul(x, 16777619);
    }
  }
  return x >>> 0;
}

function pick(arr, ...keys) {
  return arr[h(...keys) % arr.length];
}

function uniq(list) {
  return [...new Set(list.filter(Boolean))];
}

function esc(s) {
  return s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function tsArray(lines, indent = 2) {
  const pad = " ".repeat(indent);
  return lines.map((l) => `${pad}"${esc(l)}",`).join("\n");
}

