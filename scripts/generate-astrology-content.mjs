function expandOpeners(sign) {
  const seeds = OPENER_SEEDS[sign];
  const pairs = OPENER_PAIRS[sign];
  const templates = OPENER_TEMPLATES[sign];
  const out = [...seeds];
  for (let i = 0; i < pairs.length; i++) {
    for (let t = 0; t < templates.length; t++) {
      out.push(templates[t](pairs[i][0], pairs[i][1]));
    }
  }
  // Extra unique lines from hashed recombinations
  for (let i = 0; i < 40; i++) {
    const a = pick(pairs, sign, "oa", i)[0];
    const b = pick(pairs, sign, "ob", i + 7)[1];
    const line = pick(templates, sign, "ot", i)(a, b);
    out.push(line);
  }
  return uniq(out);
}

function expandElements(el) {
  return uniq([...ELEMENT_SEEDS[el], ...ELEMENT_EXPAND[el]]);
}

function expandThreads() {
  const out = [...THREAD_SEEDS, ...THREAD_SOLOS];
  for (let i = 0; i < THREAD_ACTIONS.length; i++) {
    for (let j = 0; j < THREAD_PEOPLE.length; j++) {
      const action = THREAD_ACTIONS[i];
      const person = THREAD_PEOPLE[j];
      const mid = THREAD_MIDDLES[(i * 3 + j * 5) % THREAD_MIDDLES.length];
      out.push(`${action} ${person}. ${mid}`);
    }
  }
  return uniq(out);
}

function expandClosings() {
  return uniq([...CLOSING_SEEDS, ...CLOSING_EXPAND]);
}

function expandAffirmations(sign) {
  const out = [...AFFIRM_SEEDS[sign], ...UNIVERSAL_AFFIRMATIONS];
  const stems = AFFIRM_STEMS[sign];
  const objects = AFFIRM_OBJECTS[sign];
  for (const stem of stems) {
    for (const obj of objects) {
      for (const tail of AFFIRM_TAILS) {
        // Not all combos — sample denser unique set via stride
        out.push(`${stem} ${obj}, ${tail}`);
      }
    }
  }
  // Cap per sign: ~5+ years of unique spoken lines before any repeat for that sign.
  return uniq(out).slice(0, 2000);
}

function expandBox() {
  return uniq([...BOX_SEEDS, ...BOX_EXPAND]);
}

function expandSend() {
  return uniq([...SEND_SEEDS, ...SEND_EXPAND]);
}

